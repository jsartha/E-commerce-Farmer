interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = window.localStorage.getItem('marketplace-language');
    return LANGUAGES.some(({ code }) => code === saved) ? saved as Language : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem('marketplace-language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === 'en' ? text : translations[language][text] || text,
  }), [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
      <label className="fixed bottom-4 right-4 z-[60] flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-3 py-2 text-xs font-semibold text-slate-700 shadow-lg">
        <span>{value.t('Language')}</span>
        <select
          aria-label={value.t('Language')}
          value={language}
          onChange={(event) => setLanguage(event.target.value as Language)}
          className="max-w-32 bg-transparent text-xs font-semibold text-slate-900 outline-none"
        >
          {LANGUAGES.map(({ code, name }) => <option key={code} value={code}>{name}</option>)}
        </select>
      </label>
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used within LanguageProvider.');
  return value;
};
